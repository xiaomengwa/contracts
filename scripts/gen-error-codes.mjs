/**
 * 从 bundled.yaml 的 ErrorCode/ErrorAction/ErrorCategory 枚举及
 * x-enum-descriptions / x-enum-categories / x-enum-actions 扩展
 * 生成 Go 常量文件。
 *
 * 输出: error_codes.gen.go — 包含常量定义、类型别名和中文注释
 */
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import yaml from 'js-yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const bundled = yaml.load(fs.readFileSync(path.join(root, 'bundled.yaml'), 'utf-8'));
const schemas = bundled.components?.schemas || {};

const errorCode = schemas.ErrorCode;
const errorAction = schemas.ErrorAction;
const errorCategory = schemas.ErrorCategory;

if (!errorCode?.enum) {
  console.error('❌ ErrorCode enum not found in bundled.yaml');
  process.exit(1);
}

// 手写的 Go 常量名映射，保持与 executor/internal/errorcodes/codes.go 完全一致
// 避免自动命名产生的 HTTP/ID 等缩写处理问题
const CONST_NAME_MAP = {
  INVALID_PARAM: 'CodeInvalidParam',
  UNAUTHORIZED: 'CodeUnauthorized',
  FORBIDDEN: 'CodeForbidden',
  NOT_FOUND: 'CodeNotFound',
  CONFLICT: 'CodeConflict',
  RATE_LIMITED: 'CodeRateLimited',
  QUOTA_EXCEEDED: 'CodeQuotaExceeded',
  CLIENT_CANCELED: 'CodeClientCanceled',
  SERVICE_RESTARTING: 'CodeServiceRestarting',
  MODEL_NOT_FOUND: 'CodeModelNotFound',
  ROUTE_GROUP_NOT_FOUND: 'CodeRouteGroupNotFound',
  PROVIDER_NOT_FOUND: 'CodeProviderNotFound',
  MODEL_IMAGE_INPUT_UNSUPPORTED: 'CodeModelImageInputUnsupported',
  NO_AVAILABLE_UPSTREAM: 'CodeNoAvailableUpstream',
  NO_LEASE_CAPACITY: 'CodeNoLeaseCapacity',
  UPSTREAM_ERROR: 'CodeUpstreamError',
  UPSTREAM_HTTP_ERROR: 'CodeUpstreamHTTPError',
  UPSTREAM_STREAM_ERROR: 'CodeUpstreamStreamError',
  INTERNAL_ERROR: 'CodeInternalError',
  UNSUPPORTED_STREAM_CONVERSION: 'CodeUnsupportedStreamConversion',
  REDEEM_CODE_INACTIVE: 'CodeRedeemCodeInactive',
  REDEEM_CODE_EXPIRED: 'CodeRedeemCodeExpired',
  REDEEM_CODE_EXHAUSTED: 'CodeRedeemCodeExhausted',
  REDEEM_CODE_ALREADY_REDEEMED: 'CodeRedeemCodeAlreadyRedeemed',
  REDEEM_CODE_PLAN_DOWNGRADE: 'CodeRedeemCodePlanDowngrade',
  UPSTREAM_AUTH_INVALID: 'CodeUpstreamAuthInvalid',
  UPSTREAM_PERMISSION_DENIED: 'CodeUpstreamPermissionDenied',
  UPSTREAM_MODEL_NOT_FOUND: 'CodeUpstreamModelNotFound',
  UPSTREAM_MODEL_NOT_SUPPORTED: 'CodeUpstreamModelNotSupported',
  UPSTREAM_INVALID_REQUEST: 'CodeUpstreamInvalidRequest',
  UPSTREAM_IMAGE_FORMAT_INVALID: 'CodeUpstreamImageFormatInvalid',
  UPSTREAM_REASONING_STATE_REQUIRED: 'CodeUpstreamReasoningStateRequired',
  UPSTREAM_CONTEXT_LENGTH_EXCEEDED: 'CodeUpstreamContextLengthExceeded',
  UPSTREAM_CONTENT_BLOCKED: 'CodeUpstreamContentBlocked',
  UPSTREAM_RATE_LIMITED: 'CodeUpstreamRateLimited',
  UPSTREAM_QUOTA_EXCEEDED: 'CodeUpstreamQuotaExceeded',
  UPSTREAM_BILLING_REQUIRED: 'CodeUpstreamBillingRequired',
  UPSTREAM_PLAN_EXPIRED: 'CodeUpstreamPlanExpired',
  UPSTREAM_PLAN_MODEL_DENIED: 'CodeUpstreamPlanModelDenied',
  UPSTREAM_DUPLICATE_REQUEST: 'CodeUpstreamDuplicateRequest',
  UPSTREAM_OVERLOADED: 'CodeUpstreamOverloaded',
  UPSTREAM_TIMEOUT: 'CodeUpstreamTimeout',
  UPSTREAM_INTERNAL_ERROR: 'CodeUpstreamInternalError',
};

const descriptions = errorCode['x-enum-descriptions'] || {};

let out = `// Code generated by contracts/scripts/gen-error-codes.mjs. DO NOT EDIT.
// Source: contracts/bundled.yaml → components/schemas/ErrorCode

package errorcodes

// ErrorCode is the platform error code type.
type ErrorCode = string

// Action recommends the next step for the caller.
type Action = string

// Category groups errors for display priority and reporting.
type Category = string

// ── 错误码常量 ──

const (
`;

for (const code of errorCode.enum) {
  const desc = descriptions[code] || '';
  const goName = CONST_NAME_MAP[code];
  if (!goName) {
    console.error(`⚠️  No name mapping for ${code}`);
    continue;
  }
  out += `\t// ${goName} — ${desc}\n`;
  out += `\t${goName} ErrorCode = "${code}"\n\n`;
}

out += `)

// ── 操作建议常量 ──

const (
	ActionFixRequest   Action = "fix_request"
	ActionRetryLater   Action = "retry_later"
	ActionAddQuota     Action = "add_quota"
	ActionContactAdmin Action = "contact_admin"
	ActionServerError  Action = "server_error"
	ActionCanceled     Action = "canceled"
	ActionRateLimited  Action = "rate_limited"
	ActionNoCapacity   Action = "no_capacity"
)

// ── 错误分类常量 ──

const (
	CategoryRequest           Category = "request"
	CategoryQuota             Category = "quota"
	CategoryRateLimit         Category = "rate_limit"
	CategoryUpstreamRateLimit Category = "upstream_rate_limit"
	CategoryUpstreamConfig    Category = "upstream_config"
	CategoryUpstreamRequest   Category = "upstream_request"
	CategoryUpstreamServer    Category = "upstream_server"
	CategoryCapacity          Category = "capacity"
	CategoryCanceled          Category = "canceled"
	CategoryInternal          Category = "internal"
)
`;

// Write to executor
const executorPath = path.join(root, '../executor/internal/errorcodes/error_codes.gen.go');
fs.writeFileSync(executorPath, out, 'utf-8');
console.log(`✅ Generated executor error codes: ${errorCode.enum.length} codes`);

// Write to manager (same content, different package)
const managerOut = out.replace('package errorcodes', 'package apigen');
const managerPath = path.join(root, '../manager/internal/management/apigen/error_codes.gen.go');
fs.writeFileSync(managerPath, managerOut, 'utf-8');
console.log(`✅ Generated manager error codes (package apigen)`);
